# ----------------------------------------------------------------------------
def _new_doc():
    doc = Document()
    st = doc.styles["Normal"]
    st.font.name = "宋体"
    st.font.size = Pt(10.5)
    return doc


def _title(doc, text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(16)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER


def _meta(doc, doc_no, ver, eff_from, eff_to, secrecy="内部"):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(f"文号：{doc_no}　版本：{ver}　生效：{eff_from}　失效：{eff_to}　密级：{secrecy}")
    r.italic = True
    r.font.size = Pt(9)


def _chapter(doc, title):
    p = doc.add_paragraph()
    r = p.add_run(title)
    r.bold = True
    r.font.size = Pt(13)


def _section(doc, title):
    p = doc.add_paragraph()
    r = p.add_run(title)
    r.bold = True
    r.font.size = Pt(11.5)


def _clause(doc, text):
    doc.add_paragraph(text)


def _list_items(doc, items, style="List Number"):
    for it in items:
        doc.add_paragraph(it, style=style)


def _footer_sign(doc, dept, rev_date):
    p = doc.add_paragraph("")
    p2 = doc.add_paragraph(f"主办部门：{dept}")
    p2.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    p3 = doc.add_paragraph(f"本版修订日期：{rev_date}")
    p3.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    p4 = doc.add_paragraph("页脚：本文档为银行内部制度 · 未经授权不得外传")
    p4.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for r in p4.runs:
        r.font.size = Pt(8)
        r.italic = True


